function semanticFor(
	adapter: CodemodAdapterId,
	theme?: { readonly path: string; readonly resolved: string },
): string {
	const fields: string[] = [];
	if (adapter === CodemodAdapterId.StyledComponents)
		fields.push("source: { framework: BuiltinHostFramework.React }");
	if (adapter === CodemodAdapterId.SolidStyled)
		fields.push("source: { framework: BuiltinHostFramework.Solid }");
	if (adapter === CodemodAdapterId.VueStyled)
		fields.push("source: { framework: BuiltinHostFramework.Vue }");
	if (
		adapter === CodemodAdapterId.ChakraUi ||
		adapter === CodemodAdapterId.Mui ||
		adapter === CodemodAdapterId.Mantine
	)
		fields.push("source: { framework: BuiltinHostFramework.React }");
	if (theme !== undefined) {
		fields.push(
			`themes: [{ path: ${JSON.stringify(theme.path)}, authored: "theme.${theme.path}", resolved: ${JSON.stringify(theme.resolved)} }]`,
		);
	}
	return fields.length === 0 ? "undefined" : `{ ${fields.join(", ")} }`;
}

function usesBuiltinHostFramework(adapter: CodemodAdapterId): boolean {
	return (
		adapter === CodemodAdapterId.StyledComponents ||
		adapter === CodemodAdapterId.SolidStyled ||
		adapter === CodemodAdapterId.VueStyled ||
		adapter === CodemodAdapterId.ChakraUi ||
		adapter === CodemodAdapterId.Mui ||
		adapter === CodemodAdapterId.Mantine
	);
}

function hasOfficialSourceConfig(adapter: CodemodAdapterId): boolean {
	return (
		adapter === CodemodAdapterId.Pandwind ||
		adapter === CodemodAdapterId.Panda ||
		adapter === CodemodAdapterId.ChakraUi ||
		adapter === CodemodAdapterId.Mui ||
		adapter === CodemodAdapterId.Mantine ||
		adapter === CodemodAdapterId.Tailwind ||
		adapter === CodemodAdapterId.Tokenami ||
		adapter === CodemodAdapterId.UnoCSS
	);
}

function usesLiteralThemedSource(adapter: CodemodAdapterId): boolean {
	return !hasOfficialSourceConfig(adapter);
}

function isClassProjectionTarget(adapter: CodemodAdapterId): boolean {
	return adapter === CodemodAdapterId.Tailwind || adapter === CodemodAdapterId.UnoCSS;
}

function classProjectionMarkers(adapter: CodemodAdapterId): readonly string[] {
	return adapter === CodemodAdapterId.Tailwind
		? ["text-", "bg-", "p-", "[", "className", "class"]
		: ["text-", "bg-", "p-", "[", "className", "class"];
}

function roundTripCheck(
	target: CodemodAdapterId,
	forward: string,
	reverse: string,
	label: string,
): string {
	return isClassProjectionTarget(target)
		? `expectTargetClassProjection(${forward}, ${reverse}, ${JSON.stringify(classProjectionMarkers(target))}, ${JSON.stringify(label)});`
		: `expectActionableRoundTrip(${forward}, ${reverse});`;
}

/**
 * Use a source library's documented token spelling when its official loader is
 * available. This is intentionally a small fixture selection table, not a
 * duplicate utility vocabulary: the values are only the names authored in the
 * corresponding source examples and their project fixtures.
 */
function configuredSource(adapter: CodemodAdapterId, source: string): string {
	switch (adapter) {
		case CodemodAdapterId.Pandwind:
			return source.replaceAll('"red"', '"$brand"');
		case CodemodAdapterId.Panda:
			return source
				.replaceAll('"red.300"', '"brand.500"')
				.replaceAll('"blue.300"', '"brand.500"')
				.replaceAll('"red"', '"brand.500"')
				.replaceAll('"blue"', '"brand.500"');
		case CodemodAdapterId.ChakraUi:
			return source
				.replaceAll('bg="red.200"', 'bg="brand.500"')
				.replaceAll('backgroundColor="red.200"', 'backgroundColor="brand.500"');
		case CodemodAdapterId.Mui:
			return source.replaceAll('"red"', '"primary.main"');
		case CodemodAdapterId.Mantine:
			return source.replaceAll('"blue.6"', '"brand.0"').replaceAll('"blue"', '"brand.0"');
		case CodemodAdapterId.Tailwind:
		case CodemodAdapterId.UnoCSS:
			return source.replace(/className="[^"]*"/u, 'className="text-brand p-card"');
		case CodemodAdapterId.Tokenami:
			return source.replaceAll('"red"', '"var(--color_brand)"');
		default:
			return source;
	}
}

function themedSource(adapter: CodemodAdapterId, source: string, color: string): string {
	if (hasOfficialSourceConfig(adapter)) return configuredSource(adapter, source);
	return source
		.replaceAll('"red.300"', JSON.stringify(color))
		.replaceAll('"red.200"', JSON.stringify(color))
		.replaceAll('"blue.6"', JSON.stringify(color))
		.replaceAll('"red"', JSON.stringify(color))
		.replaceAll("color: red", `color: ${color}`)
		.replaceAll("color: tomato", `color: ${color}`);
}

function tokenSource(adapter: CodemodAdapterId, source: string, color: string): string {
	if (hasOfficialSourceConfig(adapter)) return configuredSource(adapter, source);
	return source
		.replaceAll('"red.300"', JSON.stringify(color))
		.replaceAll('"red.200"', JSON.stringify(color))
		.replaceAll('"blue.6"', JSON.stringify(color))
		.replaceAll('"red"', JSON.stringify(color))
		.replaceAll("color: red", `color: ${color}`);
}

function edgeSource(adapter: CodemodAdapterId, source: string): string {
	const secondary = officialApiFamilyCases().find(
		(candidate) => candidate.adapter === adapter && candidate.expectation !== "context",
	);
	return secondary?.source ?? source;
}

function happySource(adapter: CodemodAdapterId): { file: string; source: string } {
	const fixture = officialApiCases().find((candidate) => candidate.adapter === adapter);
	if (fixture !== undefined) return { file: fixture.file, source: fixture.source };
	const contractFixture = adapterContractFixtures.find(
		(candidate) => candidate.adapter === adapter,
	);
	if (contractFixture === undefined) throw new Error(`missing route example for ${adapter}`);
	return { file: contractFixture.file, source: contractFixture.source };
}

function targetModuleFile(target: CodemodAdapterId, file: string): string {
	if (!file.endsWith(".ts")) return file;
	if (target === CodemodAdapterId.Treat) return file.replace(/\.ts$/u, ".treat.ts");
	if (target === CodemodAdapterId.VanillaExtract) return file.replace(/\.ts$/u, ".css.ts");
	return file;
}

function sourceExample(adapter: CodemodAdapterId) {
	const happy = happySource(adapter);
	const secondary = officialApiFamilyCases().find(
		(candidate) => candidate.adapter === adapter && candidate.expectation !== "context",
	);
	return {
		file: happy.file,
		happy: happy.source,
		edge: secondary?.source ?? edgeSource(adapter, happy.source),
		edgeFile: secondary?.file ?? happy.file,
		malformed: `${happy.source}\nconst unfinished = { /* unfinished ${adapter} */`,
		semantic: semanticFor(adapter),
	};
}

function sourceConstants(
	example: ReturnType<typeof sourceExample>,
	source: CodemodAdapterId,
	target: CodemodAdapterId,
): string {
	const blueColor =
		source === CodemodAdapterId.ChakraUi || target === CodemodAdapterId.ChakraUi
			? "#2a57c8"
			: "#2563eb";
	const themedInput =
		source === CodemodAdapterId.ChakraUi && target === CodemodAdapterId.UnoCSS
			? example.happy.replaceAll('bg="red.200"', 'backgroundColor="red.200"')
			: example.happy;
	return [
		`const happySource = ${JSON.stringify(example.happy)};`,
		`const edgeSource = ${JSON.stringify(example.edge)};`,
		`const malformedSource = ${JSON.stringify(example.malformed)};`,
		`const sourceSemantic = ${example.semantic};`,
		`const themedSource = ${JSON.stringify(themedSource(source, themedInput, blueColor))};`,
		`const tokenSource = ${JSON.stringify(tokenSource(source, themedInput, blueColor))};`,
		// Project loaders resolve the authored token references above. Do not add
		// synthetic theme metadata to literal source code: that changes a static
		// expression into a runtime expression and makes round-trip evidence lie.
		`const blueSemantic = ${semanticFor(source)};`,
		`const amberSemantic = ${semanticFor(source)};`,
		`const blueTargetSemantic = ${semanticFor(target)};`,
		`const amberTargetSemantic = ${semanticFor(target)};`,
		`const blueProject = createAdapterRouteProject(${identifier(source)}, ${identifier(target)}, ${JSON.stringify(blueColor)});`,
		`const amberProject = createAdapterRouteProject(${identifier(source)}, ${identifier(target)}, "#f97316");`,
	].join("\n");
}

