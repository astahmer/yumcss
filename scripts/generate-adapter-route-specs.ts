function inlineSnapshotArguments(source: string): readonly string[] {
	const marker = "toMatchInlineSnapshot(";
	const snapshots: string[] = [];
	let searchFrom = 0;
	while (true) {
		const markerStart = source.indexOf(marker, searchFrom);
		if (markerStart < 0) return snapshots;
		const argumentStart = markerStart + marker.length;
		let depth = 1;
		let quote: string | undefined;
		let escaped = false;
		let cursor = argumentStart;
		for (; cursor < source.length; cursor++) {
			const character = source[cursor]!;
			if (quote !== undefined) {
				if (escaped) {
					escaped = false;
					continue;
				}
				if (character === "\\") {
					escaped = true;
					continue;
				}
				if (character === quote) quote = undefined;
				continue;
			}
			if (character === '"' || character === "'" || character === "`") {
				quote = character;
				continue;
			}
			if (character === "(") {
				depth++;
				continue;
			}
			if (character !== ")") continue;
			depth--;
			if (depth !== 0) continue;
			snapshots.push(source.slice(argumentStart, cursor));
			break;
		}
		if (depth !== 0)
			throw new Error(`unterminated inline snapshot in generated spec at ${markerStart}`);
		searchFrom = cursor + 1;
	}
}

function preserveInlineSnapshots(generated: string, previous: string | undefined): string {
	if (previous === undefined || !previous.startsWith(generatedHeader)) return generated;
	const snapshots = inlineSnapshotArguments(previous);
	if (snapshots.length === 0) return generated;
	const placeholders = generated.match(/toMatchInlineSnapshot\(\);/g)?.length ?? 0;
	if (snapshots.length !== placeholders)
		throw new Error(
			`refusing to preserve inline snapshots: generated spec has ${placeholders} placeholders but previous spec has ${snapshots.length} snapshots`,
		);
	let index = 0;
	return generated.replaceAll("toMatchInlineSnapshot();", () => {
		const snapshot = snapshots[index++];
		return snapshot === undefined || snapshot.trim() === ""
			? "toMatchInlineSnapshot();"
			: `toMatchInlineSnapshot(${snapshot})`;
	});
}

function writeGeneratedSpec(path: string, generated: string): void {
	mkdirSync(resolve(path, ".."), { recursive: true });
	let previous: string | undefined;
	try {
		previous = readFileSync(path, "utf8");
	} catch {
		previous = undefined;
	}
	writeFileSync(path, preserveInlineSnapshots(generated, previous));
}

