/**
 * Tailwind design-system codegen — generates a typed `tw()` from a real
 * Tailwind design system.
 *
 * Loads the Tailwind design system from a CSS entry (via `@tailwindcss/node`),
 * introspects functional/static utilities, value completions and variants, then
 * writes two files next to the CSS entry:
 *
 * - `types.d.ts` — `WindVariants`: one key per utility + recursive variant keys,
 *   with literal value unions so the editor autocompletes real Tailwind classes.
 * - `tw.ts` — a typed `tw` instance wired with the design-system variant metadata.
 *
 */

import { __unstable__loadDesignSystem } from "@tailwindcss/node";
import { camelCaseProperty } from "./camelcase-property.ts";
import { TailwindTypeEmitter, utilityKey as emittedUtilityKey } from "./codegen-emitter.ts";
import { TailwindUtilityCatalog } from "./codegen-catalog.ts";

import { buildConflicts, detectModifierUtilities } from "./codegen-conflicts.ts";
export { canonicalProps } from "./codegen-conflicts.ts";
import { detectVariantJoin } from "./codegen-variants.ts";
export {
	resolveComponents,
	resolvePresetConditions,
	resolveThemes,
	resolveTokenGroups,
} from "./codegen-theme-input.ts";
const header = "// Generated by pandwind — do not edit. Run `pandwind-tw generate` to regenerate.";

type TailwindDesignSystem = Awaited<ReturnType<typeof __unstable__loadDesignSystem>>;
type DesignSystemLoader = (css: string, options: { base: string }) => Promise<TailwindDesignSystem>;
type UtilityCatalog = Pick<TailwindUtilityCatalog, "collect" | "expand">;
type TypeEmitter = Pick<TailwindTypeEmitter, "utilities" | "variants" | "runtime">;

export interface DesignSystemCodegen {
	generate(
		css: string,
		base: string,
		options?: GenerateDesignSystemOptions,
	): Promise<GeneratedDesignSystemSource>;
}

export interface DesignSystemCodegenDependencies {
	readonly loader?: DesignSystemLoader;
	readonly catalog?: UtilityCatalog;
	readonly buildConflicts?: typeof buildConflicts;
	readonly detectModifiers?: typeof detectModifierUtilities;
	readonly detectVariantJoin?: typeof detectVariantJoin;
	readonly emitter?: TypeEmitter;
}

export interface GeneratedDesignSystemSource {
	readonly typesDts: string;
	readonly twTs: string;
	readonly utilityCount: number;
	readonly variantCount: number;
}

export interface GenerateDesignSystemOptions {
	/**
	 * A generated `@theme {}` block (see generate-theme.ts) injected into the
	 * CSS before Tailwind loads it. Token-derived utilities then flow into
	 * the generated types like any other utility, so tw() autocomplete is
	 * driven by your design system's tokens. Omitted (or empty) = unchanged
	 * behavior.
	 */
	themeBlock?: string;
}

/**
 * Generate the two artifact files for a CSS entry. Exported so tests and
 * tooling can reuse it without writing to disk.
 */
class DefaultDesignSystemCodegen implements DesignSystemCodegen {
	private readonly loader: DesignSystemLoader;
	private readonly catalog: UtilityCatalog;
	private readonly buildConflicts: typeof buildConflicts;
	private readonly detectModifiers: typeof detectModifierUtilities;
	private readonly detectVariantJoin: typeof detectVariantJoin;
	private readonly emitter: TypeEmitter;

	constructor(dependencies: DesignSystemCodegenDependencies = {}) {
		this.loader = dependencies.loader ?? __unstable__loadDesignSystem;
		this.catalog = dependencies.catalog ?? new TailwindUtilityCatalog();
		this.buildConflicts = dependencies.buildConflicts ?? buildConflicts;
		this.detectModifiers = dependencies.detectModifiers ?? detectModifierUtilities;
		this.detectVariantJoin = dependencies.detectVariantJoin ?? detectVariantJoin;
		this.emitter = dependencies.emitter ?? new TailwindTypeEmitter(camelCaseProperty);
	}

	async generate(
		css: string,
		base: string,
		options: GenerateDesignSystemOptions = {},
	): Promise<GeneratedDesignSystemSource> {
		const effectiveCss = options.themeBlock ? `${css}\n${options.themeBlock}` : css;
		const system = await this.loader(effectiveCss, { base });
		const functionalKeys = system.utilities.keys("functional");
		const types = this.catalog.collect(system);
		const { conflicts, compose, wildcardValues, valueTokens } = this.buildConflicts(system, types, functionalKeys);
		this.catalog.expand(types, conflicts);
		const modifierCapable = this.detectModifiers(system, types);
		const variants: Array<{ name: string; join: ":" | "-" | "" }> = [];
		for (const variant of system.getVariants()) {
			variants.push({ name: variant.name, join: this.detectVariantJoin(system, variant) });
		}
		const utilityKeyNames = new Set(
			[...types.keys()].map((name) =>
				emittedUtilityKey(name, camelCaseProperty).replace(/^"|"$/g, ""),
			),
		);
		return {
			typesDts: `${header}
${this.emitter.utilities(types, modifierCapable)}

${this.emitter.variants(variants, utilityKeyNames)}
`,
			twTs: this.emitter.runtime(variants, conflicts, compose, wildcardValues, valueTokens),
			utilityCount: types.size,
			variantCount: variants.length,
		};
	}
}

export const createDesignSystemCodegen = (
	dependencies: DesignSystemCodegenDependencies = {},
): DesignSystemCodegen => new DefaultDesignSystemCodegen(dependencies);

export async function generateDesignSystem(
	css: string,
	base: string,
	options: GenerateDesignSystemOptions = {},
): Promise<GeneratedDesignSystemSource> {
	return createDesignSystemCodegen().generate(css, base, options);
}
