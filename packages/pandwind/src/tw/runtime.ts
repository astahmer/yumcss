/**
 * `tw` runtime: converts a Panda-like style object into Tailwind class strings.
 *
 * The heavy lifting (utility types, variants, value completions) is generated
 * from the real Tailwind design system by `tw/generate-types.ts`; this runtime
 * only knows how to walk the object and compose class names.
 *
 * ```ts
 * import { createTw } from "pandwind/tw";
 * import type { WindVariants } from "./types";
 *
 * export const tw = createTw<WindVariants>({
 *   variants: { group: { dash: true } },
 * });
 *
 * tw({ bg: "sky-600", sm: { py: "12" } }); // -> "bg-sky-600 sm:py-12"
 * tw({ group: { hover: { opacity: "100" } } }); // -> "group-hover:opacity-100"
 * ```
 */

const dashCaseRegex = /[A-Z]/g;

function dashCase(key: string): string {
	return key.replace(dashCaseRegex, (match) => `-${match.toLowerCase()}`);
}

/**
 * Utilities whose value implies an additional base utility.
 *
 * `flex-col` only sets flex-direction; without `display: flex` it does nothing.
 * Tailwind models `flex` (display) and `flex-*` (direction) as separate
 * utilities, so `{ flex: "col" }` must emit both `flex` and `flex-col`.
 */
const COMPOUND_BASES: Record<string, Set<string>> = {
	flex: new Set(["col", "row", "col-reverse", "row-reverse"]),
};

export type TwValue = string | boolean | number | Array<string | number>;
export interface TwNestedStyles
	extends Record<string, TwValue | TwNestedStyles> {}

/**
 * Design-system metadata generated by `tw/generate-types.ts`.
 *
 * `join` is the separator between a variant and its argument/child when
 * stacked: `group` + `hover` -> `group-hover` (`"-"`), `@` + `md` -> `@md`
 * (`""`), everything else defaults to `":"` (`sm` + `py` -> `sm:py-12`).
 */
export interface TwVariantsMeta {
	[name: string]: { join?: ":" | "-" | "" };
}

export interface TwOptions {
	variants?: TwVariantsMeta;
}

interface Segment {
	/** Raw (camelCase) name — used for variant metadata lookups. */
	name: string;
	/** Dash-case name — used when rendering the class prefix. */
	dashed: string;
	/** Separator between this segment and the previous one. */
	join: ":" | "-" | "";
}

function isNestedStyles(
	value: TwValue | TwNestedStyles,
): value is TwNestedStyles {
	return typeof value === "object" && value !== null && !Array.isArray(value);
}

function renderPrefix(chain: Segment[]): string {
	return chain.reduce((acc, segment, index) => {
		if (index === 0) return segment.dashed;
		return acc + segment.join + segment.dashed;
	}, "");
}

function compileStyles(
	styles: TwNestedStyles,
	chain: Segment[],
	variants: TwVariantsMeta,
	classes: string[] = [],
): string[] {
	for (const [key, value] of Object.entries(styles)) {
		if (isNestedStyles(value)) {
			// A nested object is a variant stack. The child is joined to the
			// parent with the parent's join separator (e.g. `group` -> `-`).
			const parent = chain.at(-1);
			const join =
				parent === undefined ? ":" : (variants[parent.name]?.join ?? ":");
			compileStyles(
				value,
				[...chain, { name: key, dashed: dashCase(key), join }],
				variants,
				classes,
			);
			continue;
		}

		const last = chain.at(-1);
		if (last !== undefined && (variants[last.name]?.join ?? ":") !== ":") {
			throw new Error(
				`tw: variant '${last.name}' requires a nested variant, e.g. { ${last.name}: { hover: { ... } } }`,
			);
		}

		const prefix = renderPrefix(chain);
		const dashKey = dashCase(key);
		const className = prefix ? `${prefix}:${dashKey}` : dashKey;

		if (typeof value === "boolean") {
			if (value) classes.push(className);
			continue;
		}

		if (value === "" || value == null) {
			classes.push(className);
			continue;
		}

		const parts = Array.isArray(value) ? value.map(String) : [String(value)];
		const compound = COMPOUND_BASES[key];
		if (compound && parts.some((part) => compound.has(part))) {
			classes.push(className);
		}

		for (const part of parts) {
			classes.push(part ? `${className}-${part}` : className);
		}
	}

	return classes;
}

/**
 * Create a typed `tw` function bound to a generated design-system type.
 */
export function createTw<T>(options: TwOptions = {}): (styles: T) => string {
	return (styles) =>
		compileStyles(styles as TwNestedStyles, [], options.variants ?? {}).join(
			" ",
		);
}

/**
 * Untyped convenience `tw` — useful before codegen or for throwaway styles.
 */
export function tw(styles: TwNestedStyles): string {
	return compileStyles(styles, [], {}).join(" ");
}
