/**
 * Pure `tw` compiler — walks a style object and produces the class string.
 *
 * Kept separate from `runtime.ts` so the vite plugin can statically inline
 * `tw()` calls with byte-identical output: both evaluate through this single
 * function, so there is no drift between build-time and runtime behavior.
 *
 * The heavy lifting (utility types, variants, value completions) is generated
 * from the real Tailwind design system by `tw/generate-types.ts`; this module
 * only knows how to walk the object and compose class names.
 *
 * ```ts
 * compileStyles({ bg: "sky-600", sm: { py: "12" } }, {}); // "bg-sky-600 sm:py-12"
 * ```
 */

export type TwValue = string | boolean | number | Array<string | number>;
export interface TwNestedStyles extends Record<string, TwValue | TwNestedStyles> {}

/**
 * Design-system metadata generated by `tw/generate-types.ts`.
 *
 * `join` is the separator between a variant and its argument/child when
 * stacked: `group` + `hover` -> `group-hover` (`"-"`), `@` + `md` -> `@md`
 * (`""`), everything else defaults to `":"` (`sm` + `py` -> `sm:py-12`).
 */
export interface TwVariantsMeta {
	[name: string]: { join?: ":" | "-" | "" };
}

/**
 * Generated utility conflict map — which CSS properties each utility/value
 * sets, canonicalized to longhands. Used for last-wins merging: two classes
 * conflict when their variant prefix and expanded property sets overlap.
 *
 * `"*"` is the per-utility fallback for values without an explicit entry
 * (arbitrary values, opacity-modified colors, future theme values).
 */
export interface TwConflictsMeta {
	[utility: string]: Record<string, string[]>;
}

/**
 * Utilities that intentionally compose through a shared CSS property:
 * `scale-x` + `scale-y` both set `scale`, `translate-x` + `translate-y` both
 * set `translate`, `blur` + `brightness` both set `filter`. They must never
 * merge across keys — only same-utility values conflict (last axis wins).
 */
export type TwComposeMeta = readonly string[];

const dashCaseRegex = /[A-Z]/g;

function dashCase(key: string): string {
	return key.replace(dashCaseRegex, (match) => `-${match.toLowerCase()}`);
}

/**
 * Utilities whose value implies an additional base utility.
 *
 * `flex-col` only sets flex-direction; without `display: flex` it does nothing.
 * Tailwind models `flex` (display) and `flex-*` (direction) as separate
 * utilities, so `{ flex: "col" }` must emit both `flex` and `flex-col`.
 */
const COMPOUND_BASES: Record<string, Set<string>> = {
	flex: new Set(["col", "row", "col-reverse", "row-reverse"]),
};

function isNestedStyles(value: TwValue | TwNestedStyles): value is TwNestedStyles {
	return typeof value === "object" && value !== null && !Array.isArray(value);
}

interface Emitted {
	className: string;
	signature: string;
}

const EMPTY_SIGNATURE = "";

function visit(
	styles: TwNestedStyles,
	variants: TwVariantsMeta,
	conflicts: TwConflictsMeta | undefined,
	compose: ReadonlySet<string> | undefined,
	classes: Emitted[],
	signatures: Map<string, number>,
	prefix: string,
	parentName: string | undefined,
): void {
	for (const [key, value] of Object.entries(styles)) {
		if (isNestedStyles(value)) {
			// A nested object is a variant stack. The child is joined to the
			// parent with the parent's join separator (e.g. `group` -> `-`).
			const join = parentName === undefined ? ":" : (variants[parentName]?.join ?? ":");
			const dashed = dashCase(key);
			visit(
				value,
				variants,
				conflicts,
				compose,
				classes,
				signatures,
				prefix ? `${prefix}${join}${dashed}` : dashed,
				key,
			);
			continue;
		}

		if (parentName !== undefined && (variants[parentName]?.join ?? ":") !== ":") {
			throw new Error(
				`tw: variant '${parentName}' requires a nested variant, e.g. { ${parentName}: { hover: { ... } } }`,
			);
		}

		const dashKey = dashCase(key);
		const className = prefix ? `${prefix}:${dashKey}` : dashKey;

		if (typeof value === "boolean") {
			if (value) {
				push(classes, signatures, conflicts, compose, className, prefix, dashKey, "");
			}
			continue;
		}

		if (value === "" || value == null) {
			push(classes, signatures, conflicts, compose, className, prefix, dashKey, "");
			continue;
		}

		const parts = Array.isArray(value) ? value.map(String) : [String(value)];
		const compound = COMPOUND_BASES[key];
		if (compound && parts.some((part) => compound.has(part))) {
			push(classes, signatures, conflicts, compose, className, prefix, dashKey, "");
		}

		for (const part of parts) {
			push(
				classes,
				signatures,
				conflicts,
				compose,
				part ? `${className}-${part}` : className,
				prefix,
				dashKey,
				part,
			);
		}
	}
}

function push(
	classes: Emitted[],
	signatures: Map<string, number>,
	conflicts: TwConflictsMeta | undefined,
	compose: ReadonlySet<string> | undefined,
	className: string,
	prefix: string,
	utility: string,
	value: string,
): void {
	if (conflicts === undefined) {
		classes.push({ className, signature: EMPTY_SIGNATURE });
		return;
	}

	// Opacity-modified colors (`bg-red-500/50`) share the base value's
	// properties; exact lookup first, then the modifier-stripped form.
	const props =
		conflicts[utility]?.[value] ??
		conflicts[utility]?.[value.replace(/\/\d+$/, "")] ??
		conflicts[utility]?.["*"] ??
		[];

	// Composing utilities share a CSS property with sibling keys but must
	// coexist (`scale-x` + `scale-y`): merge only within the same key.
	if (compose?.has(utility)) {
		const signature = `${prefix}|~${utility}`;
		const previous = signatures.get(signature);
		if (previous !== undefined) {
			classes[previous]!.className = "";
			signatures.delete(signature);
		}
		classes.push({ className, signature });
		signatures.set(signature, classes.length - 1);
		return;
	}

	if (props.length === 0) {
		classes.push({ className, signature: EMPTY_SIGNATURE });
		return;
	}

	// Last key wins per property: a later class drops every earlier class
	// that sets any of the same (canonicalized) property under the same
	// variant prefix. `p-6` (padding) removes `px-4` (padding-inline) because
	// their expanded longhand sets overlap.
	for (const prop of props) {
		const signature = `${prefix}|${prop}`;
		const previous = signatures.get(signature);
		if (previous !== undefined) {
			classes[previous]!.className = "";
			signatures.delete(signature);
		}
	}
	classes.push({ className, signature: EMPTY_SIGNATURE });
	for (const prop of props) {
		signatures.set(`${prefix}|${prop}`, classes.length - 1);
	}
}

/**
 * Compile a style object into a Tailwind class string.
 *
 * @param styles   panda-like style object (utility keys, nested variants)
 * @param variants variant metadata from the generated `tw.ts`
 * @param conflicts optional generated conflict map enabling last-wins merging
 * @param compose optional generated list of composing utility keys
 */
export function compileStyles(
	styles: TwNestedStyles,
	variants: TwVariantsMeta,
	conflicts?: TwConflictsMeta,
	compose?: TwComposeMeta,
): string {
	const classes: Emitted[] = [];
	const composeSet = compose === undefined ? undefined : new Set(compose);
	visit(styles, variants, conflicts, composeSet, classes, new Map(), "", undefined);
	return classes
		.map((emitted) => emitted.className)
		.filter(Boolean)
		.join(" ");
}
