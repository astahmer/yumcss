/**
 * Pure `tw` compiler — walks a style object and produces the class string.
 *
 * Kept separate from `runtime.ts` so the vite plugin can statically inline
 * `tw()` calls with byte-identical output: both evaluate through this single
 * function, so there is no drift between build-time and runtime behavior.
 *
 * The heavy lifting (utility types, variants, value completions) is generated
 * from the real Tailwind design system by `tw/generate-types.ts`; this module
 * only knows how to walk the object and compose class names.
 *
 * ```ts
 * compileStyles({ bg: "sky-600", sm: { py: "12" } }, {}); // "bg-sky-600 sm:py-12"
 * ```
 */

export type TwValue = string | boolean | number | Array<string | number | boolean>;
export interface TwNestedStyles extends Record<string, TwValue | TwNestedStyles> {}

/**
 * Design-system metadata generated by `tw/generate-types.ts`.
 *
 * `join` is the separator between a variant and its argument/child when
 * stacked: `group` + `hover` -> `group-hover` (`"-"`), `@` + `md` -> `@md`
 * (`""`), everything else defaults to `":"` (`sm` + `py` -> `sm:py-12`).
 */
export interface TwVariantsMeta {
	[name: string]: { join?: ":" | "-" | "" };
}

/**
 * Generated utility conflict map — which CSS properties each utility/value
 * sets, canonicalized to longhands. Used for last-wins merging: two classes
 * conflict when their variant prefix and expanded property sets overlap.
 *
 * `"*"` is the per-utility fallback for values without an explicit entry
 * (arbitrary values, opacity-modified colors, future theme values).
 */
export interface TwConflictsMeta {
	[utility: string]: Record<string, string[]>;
}

/**
 * Utilities that intentionally compose through a shared CSS property:
 * `scale-x` + `scale-y` both set `scale`, `translate-x` + `translate-y` both
 * set `translate`, `blur` + `brightness` both set `filter`. They must never
 * merge across keys — only same-utility values conflict (last axis wins).
 */
export type TwComposeMeta = readonly string[];

const dashCaseRegex = /[A-Z]/g;

function dashCase(key: string): string {
	return key.replace(dashCaseRegex, (match) => `-${match.toLowerCase()}`);
}

/**
 * Utilities whose value implies an additional base utility.
 *
 * `flex-col` only sets flex-direction; without `display: flex` it does nothing.
 * Tailwind models `flex` (display) and `flex-*` (direction) as separate
 * utilities, so `{ flex: "col" }` must emit both `flex` and `flex-col`.
 */
const COMPOUND_BASES: Record<string, Set<string>> = {
	flex: new Set(["col", "row", "col-reverse", "row-reverse"]),
};

/**
 * Semantic sub-keys for overloaded utilities — additive sugar that keeps the
 * plain Tailwind spelling working.
 *
 * Tailwind overloads one class prefix for several unrelated CSS concerns:
 * `text-2xl` (size), `text-gray-900` (color) and `text-center` (alignment)
 * share the `text` key. A sub-key names the concern explicitly and resolves
 * onto the SAME underlying utility, so `{ textSize: "2xl" }` emits exactly
 * `text-2xl`:
 *
 * ```ts
 * tw({ textSize: "2xl", textColor: "gray-900" }); // "text-2xl text-gray-900"
 * ```
 *
 * Conflict semantics come from the generated per-property conflict map of
 * the BASE utility: `{ text: "sm", textSize: "lg" }` merges last-wins
 * (both set font-size), while `{ textSize: "2xl", textColor: "gray-900" }`
 * composes (disjoint properties).
 *
 * The typegen pipeline imports this table so generated types expose exactly
 * these spellings — one source of truth for runtime and types.
 */
export const UTILITY_SUBKEYS: Readonly<Record<string, string>> = {
	textColor: "text",
	textOverflow: "text",
	textAlign: "text",
	textSize: "text",
	textWrap: "text",
	// bg family (unambiguous concerns only — see plans/007 item C Outcomes):
	bgColor: "bg",
	bgImage: "bg",
	bgSize: "bg",
	bgPosition: "bg",
	bgRepeat: "bg",
	bgAttachment: "bg",
	// border family:
	borderColor: "border",
	borderWidth: "border",
	borderStyle: "border",
	// outline family:
	outlineColor: "outline",
	outlineWidth: "outline",
	outlineStyle: "outline",
	// decoration family (the API's key for `decoration-*` utilities; the
	// line concern lives under separate keys like `underline`/`no`/`line`,
	// so there is no overloaded base to split there):
	decorationColor: "decoration",
	decorationStyle: "decoration",
	decorationThickness: "decoration",
};

function isNestedStyles(value: TwValue | TwNestedStyles): value is TwNestedStyles {
	return typeof value === "object" && value !== null && !Array.isArray(value);
}

interface Emitted {
	className: string;
	/** Conflict signatures still contributed by this emitted class. */
	ownedSignatures: string[];
}

function visit(
	styles: TwNestedStyles,
	variants: TwVariantsMeta,
	conflicts: TwConflictsMeta | undefined,
	compose: ReadonlySet<string> | undefined,
	classes: Emitted[] | string[],
	signatures: Map<string, number> | undefined,
	prefix: string,
	parentName: string | undefined,
): void {
	for (const key of Object.keys(styles)) {
		const value = styles[key]!;
		if (isNestedStyles(value)) {
			// A nested object is a variant stack. The child is joined to the
			// parent with the parent's join separator (e.g. `group` -> `-`).
			const join = parentName === undefined ? ":" : (variants[parentName]?.join ?? ":");
			const dashed = dashCase(key);
			visit(
				value,
				variants,
				conflicts,
				compose,
				classes,
				signatures,
				prefix ? `${prefix}${join}${dashed}` : dashed,
				key,
			);
			continue;
		}

		if (parentName !== undefined && (variants[parentName]?.join ?? ":") !== ":") {
			throw new Error(
				`tw: variant '${parentName}' requires a nested variant, e.g. { ${parentName}: { hover: { ... } } }`,
			);
		}

		// Sub-keys resolve onto their base utility: `textSize` emits `text-*`
		// classes and shares the base's conflict-map entries.
		const utility = UTILITY_SUBKEYS[key] ?? dashCase(key);
		const className = prefix ? `${prefix}:${utility}` : utility;

		if (typeof value === "boolean") {
			if (value) {
				push(classes, signatures, conflicts, compose, className, prefix, utility, "");
			}
			continue;
		}

		if (value === "" || value == null) {
			push(classes, signatures, conflicts, compose, className, prefix, utility, "");
			continue;
		}

		// Array values can mix plain values with a bare boolean flag (e.g. a
		// compound base's implied class merged alongside an explicit value by
		// the codemod's collision handling) — `true` must resolve to the
		// bare utility exactly like the scalar boolean branch above, not the
		// literal string "true".
		const rawParts = Array.isArray(value) ? value : [value];
		const hasBareFlag = rawParts.includes(true);
		const parts = rawParts.filter((part) => typeof part !== "boolean").map(String);
		const compound = COMPOUND_BASES[key];
		if (hasBareFlag || (compound && parts.some((part) => compound.has(part)))) {
			push(classes, signatures, conflicts, compose, className, prefix, utility, "");
		}

		for (const part of parts) {
			push(
				classes,
				signatures,
				conflicts,
				compose,
				part ? `${className}-${part}` : className,
				prefix,
				utility,
				part,
			);
		}
	}
}

function push(
	classes: Emitted[] | string[],
	signatures: Map<string, number> | undefined,
	conflicts: TwConflictsMeta | undefined,
	compose: ReadonlySet<string> | undefined,
	className: string,
	prefix: string,
	utility: string,
	value: string,
): void {
	if (conflicts === undefined) {
		(classes as string[]).push(className);
		return;
	}
	const emittedClasses = classes as Emitted[];
	const conflictSignatures = signatures!;

	// Opacity-modified colors (`bg-red-500/50`) share the base value's
	// properties; exact lookup first, then the modifier-stripped form.
	const props =
		conflicts[utility]?.[value] ??
		conflicts[utility]?.[value.replace(/\/\d+$/, "")] ??
		conflicts[utility]?.["*"] ??
		[];

	// Composing utilities share a CSS property with sibling keys but must
	// coexist (`scale-x` + `scale-y`): merge only within the same key.
	if (compose?.has(utility)) {
		const signature = `${prefix}|~${utility}`;
		const previous = conflictSignatures.get(signature);
		if (previous !== undefined) {
			emittedClasses[previous]!.className = "";
			emittedClasses[previous]!.ownedSignatures = [];
			conflictSignatures.delete(signature);
		}
		emittedClasses.push({ className, ownedSignatures: [signature] });
		conflictSignatures.set(signature, emittedClasses.length - 1);
		return;
	}

	if (props.length === 0) {
		emittedClasses.push({ className, ownedSignatures: [] });
		return;
	}

	// Last key wins per property. When a later class overlaps only part of an
	// earlier multi-property utility, keep the earlier class for its surviving
	// longhands (`p-6 pb-10` must retain `p-6` for top/inline padding).
	const ownedSignatures = props.map((prop) => `${prefix}|${prop}`);
	for (const prop of props) {
		const signature = `${prefix}|${prop}`;
		const previous = conflictSignatures.get(signature);
		if (previous !== undefined) {
			const previousOwned = emittedClasses[previous]!.ownedSignatures;
			const ownedIndex = previousOwned.indexOf(signature);
			if (ownedIndex !== -1) previousOwned.splice(ownedIndex, 1);
			if (previousOwned.length === 0) emittedClasses[previous]!.className = "";
			conflictSignatures.delete(signature);
		}
	}
	emittedClasses.push({ className, ownedSignatures });
	for (const signature of ownedSignatures) {
		conflictSignatures.set(signature, emittedClasses.length - 1);
	}
}

/**
 * Compile a style object into a Tailwind class string.
 *
 * @param styles   panda-like style object (utility keys, nested variants)
 * @param variants variant metadata from the generated `tw.ts`
 * @param conflicts optional generated conflict map enabling last-wins merging
 * @param compose optional generated list of composing utility keys
 */
export function compileStyles(
	styles: TwNestedStyles,
	variants: TwVariantsMeta,
	conflicts?: TwConflictsMeta,
	compose?: TwComposeMeta | ReadonlySet<string>,
): string {
	if (conflicts === undefined) {
		const classes: string[] = [];
		visit(styles, variants, conflicts, undefined, classes, undefined, "", undefined);
		return classes.join(" ");
	}
	const classes: Emitted[] = [];
	const composeSet = compose === undefined || compose instanceof Set ? compose : new Set(compose);
	visit(styles, variants, conflicts, composeSet, classes, new Map(), "", undefined);
	let output = "";
	for (const emitted of classes) {
		if (emitted.className === "") continue;
		if (output !== "") output += " ";
		output += emitted.className;
	}
	return output;
}
