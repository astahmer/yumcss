/**
 * Tailwind bridge generation — generates `bridge.ts` for the Pandwind css()
 * adapter.
 *
 * The bridge is the inverted Tailwind design system scoped to what the
 * app's preset can produce: `(property, resolved value) -> utility`. It is
 * generated from the app's real `tailwind.css` (so `@theme` mirrors become
 * short utilities) and only keeps theme-derived values the preset tokens
 * can emit — literal values (flex, relative, ...) always stay.
 *
 * The generated module exports `bridge`, the `variants` metadata and a
 * ready `twAdapter` (`createTwAdapter` bound to the preset), so app code
 * and the vite plugin share one instance:
 *
 *   import { twAdapter } from "./bridge";
 *   export const dcss = createDesignCss(examplePreset, { className: twAdapter });
 *   // vite.config.ts
 *   plugins: [pandwindCssVite(examplePreset, { className: twAdapter }), ...]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { BRIDGE_PROPS, generateUtilityBridge } from "./bridge.ts";
import { extractTwConfig } from "../vite/inline.ts";
import { buildPandwindInteropArtifact } from "./interop-artifact.ts";

export interface GenerateTwBridgeOptions {
	readonly cssEntry: string;
	readonly twFile: string;
	readonly outFile: string;
	readonly presetImport: string;
	readonly presetExport: string;
}

export interface GeneratedTwBridge {
	readonly outFile: string;
	readonly interopFile?: string;
	readonly propertyCount: number;
}

export interface TwBridgeGenerator {
	generate(options: GenerateTwBridgeOptions): Promise<GeneratedTwBridge>;
}

type PresetModule = {
	readonly tokens?: Record<string, Record<string, unknown>>;
};

class DefaultTwBridgeGenerator implements TwBridgeGenerator {
	async generate(options: GenerateTwBridgeOptions): Promise<GeneratedTwBridge> {
		const css = readFileSync(options.cssEntry, "utf8");
		const preset = (await import(options.presetImport))[options.presetExport] as PresetModule;

		// Only values proven by the target preset can be shortened to a token
		// utility. Literal CSS values remain available through the bridge's
		// property-preserving fallback.
		const values = new Set<string>();
		for (const group of Object.values(preset.tokens ?? {})) {
			for (const value of Object.values(group)) {
				if (typeof value === "string") values.add(value);
			}
		}

		const bridge = await generateUtilityBridge(css, resolve(options.cssEntry, ".."), {
			props: BRIDGE_PROPS,
			values,
		});

		const twSource = readFileSync(options.twFile, "utf8");
		const config = extractTwConfig(twSource);
		if (config === undefined) {
			throw new Error(`pandwind: could not read the tw() config from ${options.twFile}`);
		}

		const out = `// Generated by pandwind — do not edit. Run \`pandwind-tw generate --bridge\` to regenerate.
import { createTwAdapter } from "pandwind/tw";
import { ${options.presetExport} } from "${options.presetImport}";

/** (property, resolved value) -> Tailwind utility, scoped to the preset. */
export const bridge = ${JSON.stringify(bridge)} as const;

/** Variant metadata mirrored from the generated tw.ts. */
export const variants = ${JSON.stringify(config.variants)} as const;

/** css() class strategy: emit the same utilities tw() emits. */
export const twAdapter = createTwAdapter({
	preset: ${options.presetExport},
	variants,
	bridge,
});
`;

		writeFileSync(options.outFile, out);

		const interopPath = resolve(dirname(options.outFile), "pandwind.interop.json");
		const typesPath = resolve(dirname(options.twFile), "types.d.ts");
		if (existsSync(typesPath)) {
			const themePath = resolve(dirname(options.outFile), "pandwind-theme.css");
			const artifact = buildPandwindInteropArtifact({
				typesDts: readFileSync(typesPath, "utf8"),
				twTs: twSource,
				bridge,
				artifactDir: dirname(options.outFile),
				themeBlock: existsSync(themePath) ? readFileSync(themePath, "utf8") : "",
			});
			writeFileSync(interopPath, `${JSON.stringify(artifact, null, "\t")}\n`);
			return {
				outFile: options.outFile,
				interopFile: interopPath,
				propertyCount: Object.keys(bridge).length,
			};
		}

		return { outFile: options.outFile, propertyCount: Object.keys(bridge).length };
	}
}

export const createTwBridgeGenerator = (): TwBridgeGenerator => new DefaultTwBridgeGenerator();

export const generateTwBridge = async (
	options: GenerateTwBridgeOptions,
): Promise<GeneratedTwBridge> => createTwBridgeGenerator().generate(options);
