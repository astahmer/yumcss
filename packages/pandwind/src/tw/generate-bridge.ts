/**
 * pandwind bridge codegen — generates `bridge.ts` for the tailwind css()
 * adapter.
 *
 * The bridge is the inverted Tailwind design system scoped to what the
 * app's preset can produce: `(property, resolved value) -> utility`. It is
 * generated from the app's real `tailwind.css` (so `@theme` mirrors become
 * short utilities) and only keeps theme-derived values the preset tokens
 * can emit — literal values (flex, relative, ...) always stay.
 *
 * Usage:
 *   tsx generate-bridge.ts <css-entry> <tw-file> <out-file> [preset-import] [preset-export]
 *
 * Example:
 *   tsx generate-bridge.ts ./src/tailwind.css ./src/tw.ts ./src/bridge.ts
 *
 * The generated module exports `bridge`, the `variants` metadata and a
 * ready `twAdapter` (`createTwAdapter` bound to the preset), so app code
 * and the vite plugin share one instance:
 *
 *   import { twAdapter } from "./bridge";
 *   export const dcss = createDesignCss(examplePreset, { className: twAdapter });
 *   // vite.config.ts
 *   plugins: [pandwindCssVite(examplePreset, { className: twAdapter }), ...]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { BRIDGE_PROPS, generateUtilityBridge } from "./bridge.ts";
import { extractTwConfig } from "../vite/inline.ts";
import { buildPandwindInteropArtifact } from "./interop-artifact.ts";

const [, , cssEntryArg, twFileArg, outFileArg, presetImportArg, presetExportArg] = process.argv;
const cwd = process.cwd();
const cssEntry = resolve(cwd, cssEntryArg ?? "src/tailwind.css");
const twFile = resolve(cwd, twFileArg ?? "src/tw.ts");
const outFile = resolve(cwd, outFileArg ?? "src/bridge.ts");
const presetImport = presetImportArg ?? "pandwind/preset";
const presetExport = presetExportArg ?? "examplePreset";

const css = readFileSync(cssEntry, "utf8");
const preset = (await import(presetImport))[presetExport] as {
	tokens?: Record<string, Record<string, unknown>>;
};

// Every concrete value the preset tokens can produce — the only theme
// values the bridge needs to resolve to short utilities.
const values = new Set<string>();
for (const group of Object.values(preset.tokens ?? {})) {
	for (const value of Object.values(group)) {
		if (typeof value === "string") values.add(value);
	}
}

const bridge = await generateUtilityBridge(css, resolve(cssEntry, ".."), {
	props: BRIDGE_PROPS,
	values,
});

const twSource = readFileSync(twFile, "utf8");
const config = extractTwConfig(twSource);
if (config === undefined) {
	throw new Error(`pandwind: could not read the tw() config from ${twFile}`);
}

const json = JSON.stringify(bridge);
const variantsJson = JSON.stringify(config.variants);

const out = `// Generated by pandwind — do not edit. Run \`nub run tw:bridge\` to regenerate.
import { createTwAdapter } from "pandwind/tw";
import { ${presetExport} } from "${presetImport}";

/** (property, resolved value) -> Tailwind utility, scoped to the preset. */
export const bridge = ${json} as const;

/** Variant metadata mirrored from the generated tw.ts. */
export const variants = ${variantsJson} as const;

/** css() class strategy: emit the same utilities tw() emits. */
export const twAdapter = createTwAdapter({
	preset: ${presetExport},
	variants,
	bridge,
});
`;

writeFileSync(outFile, out);

const interopPath = resolve(dirname(outFile), "pandwind.interop.json");
const typesPath = resolve(dirname(twFile), "types.d.ts");
if (existsSync(typesPath)) {
	const themePath = resolve(dirname(outFile), "pandwind-theme.css");
	const artifact = buildPandwindInteropArtifact({
		typesDts: readFileSync(typesPath, "utf8"),
		twTs: twSource,
		bridge,
		artifactDir: dirname(outFile),
		themeBlock: existsSync(themePath) ? readFileSync(themePath, "utf8") : "",
	});
	writeFileSync(interopPath, `${JSON.stringify(artifact, null, "\t")}\n`);
}
console.log(`pandwind: wrote ${outFile} (${Object.keys(bridge).length} properties)`);
