/**
 * Pure `tw` compiler — walks a style object and produces the class string.
 *
 * Kept separate from `runtime.ts` so the vite plugin can statically inline
 * `tw()` calls with byte-identical output: both evaluate through this single
 * function, so there is no drift between build-time and runtime behavior.
 *
 * The heavy lifting (utility types, variants, value completions) is generated
 * from the real Tailwind design system by the `yumcss-codemod tw generate` command; this module
 * only knows how to walk the object and compose class names.
 *
 * ```ts
 * compileStyles({ bg: "sky-600", sm: { py: "12" } }, {}); // "bg-sky-600 sm:py-12"
 * ```
 */

import { dashCase } from "../lib/utils.ts";

/** Scalar or finite-list value accepted by the pure `tw` compiler. */
export type TwValue = string | boolean | number | Array<string | number | boolean>;

/**
 * Nested utility object accepted by `compileStyles` and `createTw`.
 *
 * @category tailwind
 * @since 0.1.0
 */
export interface TwNestedStyles extends Record<string, TwValue | TwNestedStyles> {}

/**
 * Variant metadata generated by `yumcss-codemod tw generate`.
 *
 * `join` controls how a nested variant is written: `"-"` produces
 * `group-hover`, `""` produces `@md`, and the default `":"` produces
 * `sm:py-12`.
 *
 * @category tailwind
 * @since 0.1.0
 */
export interface TwVariantsMeta {
	[name: string]: { join?: ":" | "-" | "" };
}

/**
 * Generated utility conflict map used for last-wins merging.
 *
 * Entries are canonicalized to the CSS properties a utility sets; the
 * per-utility `"*"` entry covers values without a more specific mapping.
 * Utilities conflict when their variant scope and expanded properties overlap.
 *
 * @category tailwind
 * @since 0.1.0
 */
export interface TwConflictsMeta {
	[utility: string]: Record<string, string[]>;
}

/**
 * Directional utility-group conflicts that CSS property overlap cannot model.
 * A later broad group may remove an earlier narrow group, but not the reverse.
 * The codegen lane derives this from the active Tailwind merge contract.
 */
export interface TwDirectionalConflictsMeta {
	readonly kills: Readonly<Record<string, readonly string[]>>;
}

/**
 * Utilities that compose through a shared CSS property instead of replacing it.
 *
 * For example, `scale-x` and `scale-y` both contribute to `scale`, so they
 * must not merge across utility keys.
 *
 * @category tailwind
 * @since 0.1.0
 */
export type TwComposeMeta = readonly string[];

/**
 * Generated raw-value to token-spelling map used for exact remaps.
 *
 * @category tailwind
 * @since 0.1.0
 */
export interface TwValueTokensMeta {
	[utility: string]: Readonly<Record<string, string>>;
}

/**
 * Utilities whose value implies an additional base utility.
 *
 * `flex-col` only sets flex-direction; without `display: flex` it does nothing.
 * Tailwind models `flex` (display) and `flex-*` (direction) as separate
 * utilities, so `{ flex: "col" }` must emit both `flex` and `flex-col`.
 */
const COMPOUND_BASES: Record<string, Set<string>> = {
	flex: new Set(["col", "row", "col-reverse", "row-reverse"]),
};

/**
 * Semantic sub-keys for overloaded utilities — additive sugar that keeps the
 * plain Tailwind spelling working.
 *
 * Tailwind overloads one class prefix for several unrelated CSS concerns:
 * `text-2xl` (size), `text-gray-900` (color) and `text-center` (alignment)
 * share the `text` key. A sub-key names the concern explicitly and resolves
 * onto the SAME underlying utility, so `{ textSize: "2xl" }` emits exactly
 * `text-2xl`:
 *
 * ```ts
 * tw({ textSize: "2xl", textColor: "gray-900" }); // "text-2xl text-gray-900"
 * ```
 *
 * Conflict semantics use the generated per-property conflict map. Typed
 * sub-keys retain their own CSS concern so arbitrary values do not fall back
 * to another concern's wildcard properties.
 *
 * The typegen pipeline imports this table so generated types expose exactly
 * these spellings — one source of truth for runtime and types.
 */
export const UTILITY_SUBKEYS: Readonly<Record<string, string>> = {
	textColor: "text",
	textOverflow: "text",
	textAlign: "text",
	textSize: "text",
	textWrap: "text",
	// bg family (unambiguous concerns only — see plans/007 item C Outcomes):
	bgColor: "bg",
	bgImage: "bg",
	bgSize: "bg",
	bgPosition: "bg",
	bgRepeat: "bg",
	bgAttachment: "bg",
	// border family:
	borderColor: "border",
	borderWidth: "border",
	borderStyle: "border",
	// outline family:
	outlineColor: "outline",
	outlineWidth: "outline",
	outlineStyle: "outline",
	// decoration family (the API's key for `decoration-*` utilities; the
	// line concern lives under separate keys like `underline`/`no`/`line`,
	// so there is no overloaded base to split there):
	decorationColor: "decoration",
	decorationStyle: "decoration",
	decorationThickness: "decoration",
};

const UTILITY_SUBKEY_PROPERTIES: Readonly<Record<string, readonly string[]>> = {
	textColor: ["color"],
	textOverflow: ["text-overflow"],
	textAlign: ["text-align"],
	textSize: ["font-size"],
	textWrap: ["text-wrap"],
	bgColor: ["background-color"],
	bgImage: ["background-image"],
	bgSize: ["background-size"],
	bgPosition: ["background-position"],
	bgRepeat: ["background-repeat"],
	bgAttachment: ["background-attachment"],
	borderColor: [
		"border-top-color",
		"border-right-color",
		"border-bottom-color",
		"border-left-color",
	],
	borderWidth: [
		"border-top-width",
		"border-right-width",
		"border-bottom-width",
		"border-left-width",
	],
	borderStyle: [
		"border-top-style",
		"border-right-style",
		"border-bottom-style",
		"border-left-style",
	],
	outlineColor: ["outline-color"],
	outlineWidth: ["outline-width"],
	outlineStyle: ["outline-style"],
	decorationColor: ["text-decoration-color"],
	decorationStyle: ["text-decoration-style"],
	decorationThickness: ["text-decoration-thickness"],
};

const BORDER_COLOR_PROPERTIES: Readonly<Record<string, readonly string[]>> = {
	border: ["border-top-color", "border-right-color", "border-bottom-color", "border-left-color"],
	"border-x": ["border-left-color", "border-right-color"],
	"border-y": ["border-top-color", "border-bottom-color"],
	"border-t": ["border-top-color"],
	"border-r": ["border-right-color"],
	"border-b": ["border-bottom-color"],
	"border-l": ["border-left-color"],
	"border-s": ["border-inline-start-color"],
	"border-e": ["border-inline-end-color"],
	"border-bs": ["border-block-start-color"],
	"border-be": ["border-block-end-color"],
};

const borderColorProperties = (utility: string, value: string): readonly string[] | undefined => {
	if (!value.startsWith("[") || !value.endsWith("]")) return undefined;
	const rawValue = value.slice(1, -1);
	if (!/^(?:color:|#|(?:rgb|hsl|hwb|lab|lch|oklab|oklch|color)\()/iu.test(rawValue))
		return undefined;
	return BORDER_COLOR_PROPERTIES[utility];
};

function isNestedStyles(value: TwValue | TwNestedStyles): value is TwNestedStyles {
	return typeof value === "object" && value !== null && !Array.isArray(value);
}

interface Emitted {
	className: string;
	/** Conflict signatures still contributed by this emitted class. */
	ownedSignatures: string[];
}

function visit(
	styles: TwNestedStyles,
	variants: TwVariantsMeta,
	conflicts: TwConflictsMeta | undefined,
	compose: ReadonlySet<string> | undefined,
	classes: Emitted[] | string[],
	signatures: Map<string, number> | undefined,
	prefix: string,
	parentName: string | undefined,
	valueTokens: TwValueTokensMeta | undefined,
): void {
	const frames: Array<{
		styles: TwNestedStyles;
		keys: string[];
		index: number;
		prefix: string;
		parentName: string | undefined;
	}> = [{ styles, keys: Object.keys(styles), index: 0, prefix, parentName }];
	const active = new WeakSet<object>();
	active.add(styles);
	while (frames.length > 0) {
		const frame = frames.at(-1)!;
		const key = frame.keys[frame.index++];
		if (key === undefined) {
			frames.pop();
			active.delete(frame.styles);
			continue;
		}
		const value = frame.styles[key]!;
		if (isNestedStyles(value)) {
			if (active.has(value)) continue;
			// A nested object is a variant stack. The child is joined to the
			// parent with the parent's join separator (e.g. `group` -> `-`).
			const join = frame.parentName === undefined ? ":" : (variants[frame.parentName]?.join ?? ":");
			const dashed = dashCase(key);
			active.add(value);
			frames.push({
				styles: value,
				keys: Object.keys(value),
				index: 0,
				prefix: frame.prefix ? `${frame.prefix}${join}${dashed}` : dashed,
				parentName: key,
			});
			continue;
		}

		if (frame.parentName !== undefined && (variants[frame.parentName]?.join ?? ":") !== ":") {
			throw new Error(
				`tw: variant '${parentName}' requires a nested variant, e.g. { ${parentName}: { hover: { ... } } }`,
			);
		}

		// Sub-keys resolve onto their base utility: `textSize` emits `text-*`
		// classes while retaining the more specific CSS property for conflicts.
		const utility = UTILITY_SUBKEYS[key] ?? dashCase(key);
		const subkeyProperties = UTILITY_SUBKEY_PROPERTIES[key];
		const className = frame.prefix ? `${frame.prefix}:${utility}` : utility;

		if (typeof value === "boolean") {
			if (value) {
				push(
					classes,
					signatures,
					conflicts,
					compose,
					className,
					frame.prefix,
					utility,
					"",
					subkeyProperties,
				);
			}
			continue;
		}

		if (value === "" || value == null) {
			push(
				classes,
				signatures,
				conflicts,
				compose,
				className,
				frame.prefix,
				utility,
				"",
				subkeyProperties,
			);
			continue;
		}

		// Array values can mix plain values with a bare boolean flag (e.g. a
		// compound base's implied class merged alongside an explicit value by
		// the codemod's collision handling) — `true` must resolve to the
		// bare utility exactly like the scalar boolean branch above, not the
		// literal string "true".
		const rawParts = Array.isArray(value) ? value : [value];
		const hasBareFlag = rawParts.includes(true);
		const parts = rawParts.filter((part) => typeof part !== "boolean").map(String);
		const compound = COMPOUND_BASES[key];
		if (hasBareFlag || (compound && parts.some((part) => compound.has(part)))) {
			push(
				classes,
				signatures,
				conflicts,
				compose,
				className,
				frame.prefix,
				utility,
				"",
				subkeyProperties,
			);
		}

		for (const part of parts) {
			// Dynamic-but-bounded raw values remap to the configured token
			// spelling when the catalog proves an exact value match (the catalog
			// only contains entries derived from real class-list candidates of
			// this utility, keyed by whole resolved values). Opacity modifiers
			// like `#3182ce/50` never match a catalog key, so they stay raw.
			const token = valueTokens?.[utility]?.[part] ?? part;
			push(
				classes,
				signatures,
				conflicts,
				compose,
				token ? `${className}-${token}` : className,
				frame.prefix,
				utility,
				token,
				subkeyProperties,
			);
		}
	}
}

function push(
	classes: Emitted[] | string[],
	signatures: Map<string, number> | undefined,
	conflicts: TwConflictsMeta | undefined,
	compose: ReadonlySet<string> | undefined,
	className: string,
	prefix: string,
	utility: string,
	value: string,
	subkeyProperties?: readonly string[],
): void {
	if (conflicts === undefined) {
		(classes as string[]).push(className);
		return;
	}
	const emittedClasses = classes as Emitted[];
	const conflictSignatures = signatures!;

	// Opacity-modified colors (`bg-red-500/50`) share the base value's
	// properties; exact lookup first, then the modifier-stripped form.
	const exactProperties =
		conflicts[utility]?.[value] ?? conflicts[utility]?.[value.replace(/\/\d+$/, "")];
	const arbitraryProperties = value.startsWith("[")
		? (subkeyProperties ?? borderColorProperties(utility, value))
		: undefined;
	const props = exactProperties ?? arbitraryProperties ?? conflicts[utility]?.["*"] ?? [];

	// Composing utilities share a CSS property with sibling keys but must
	// coexist (`scale-x` + `scale-y`): merge only within the same key.
	if (compose?.has(utility)) {
		const signature = `${prefix}|~${utility}`;
		const previous = conflictSignatures.get(signature);
		if (previous !== undefined) {
			emittedClasses[previous]!.className = "";
			emittedClasses[previous]!.ownedSignatures = [];
			conflictSignatures.delete(signature);
		}
		emittedClasses.push({ className, ownedSignatures: [signature] });
		conflictSignatures.set(signature, emittedClasses.length - 1);
		return;
	}

	if (props.length === 0) {
		emittedClasses.push({ className, ownedSignatures: [] });
		return;
	}

	// Last key wins per property. When a later class overlaps only part of an
	// earlier multi-property utility, keep the earlier class for its surviving
	// longhands (`p-6 pb-10` must retain `p-6` for top/inline padding).
	const ownedSignatures = props.map((prop) => `${prefix}|${prop}`);
	for (const prop of props) {
		const signature = `${prefix}|${prop}`;
		const previous = conflictSignatures.get(signature);
		if (previous !== undefined) {
			const previousOwned = emittedClasses[previous]!.ownedSignatures;
			const ownedIndex = previousOwned.indexOf(signature);
			if (ownedIndex !== -1) previousOwned.splice(ownedIndex, 1);
			if (previousOwned.length === 0) emittedClasses[previous]!.className = "";
			conflictSignatures.delete(signature);
		}
	}
	emittedClasses.push({ className, ownedSignatures });
	for (const signature of ownedSignatures) {
		conflictSignatures.set(signature, emittedClasses.length - 1);
	}
}

/**
 * Compile a style object into a Tailwind class string.
 *
 * @example
 * ```ts
 * compileStyles({ bg: "sky-600", sm: { py: "12" } }, {});
 * // "bg-sky-600 sm:py-12"
 * ```
 *
 * @param styles - Utility keys and nested variants.
 * @param variants - Generated variant metadata.
 * @param conflicts - Optional conflict map for last-wins merging.
 * @param compose - Optional composing utility keys.
 * @param valueTokens - Optional exact raw-value token map.
 * @returns A space-separated class string.
 * @category tailwind
 * @since 0.1.0
 */
export function compileStyles(
	styles: TwNestedStyles,
	variants: TwVariantsMeta,
	conflicts?: TwConflictsMeta,
	compose?: TwComposeMeta | ReadonlySet<string>,
	valueTokens?: TwValueTokensMeta,
): string {
	if (!isNestedStyles(styles)) return "";
	if (conflicts === undefined) {
		const classes: string[] = [];
		visit(styles, variants, conflicts, undefined, classes, undefined, "", undefined, valueTokens);
		return classes.join(" ");
	}
	const classes: Emitted[] = [];
	const composeSet = compose === undefined || compose instanceof Set ? compose : new Set(compose);
	visit(styles, variants, conflicts, composeSet, classes, new Map(), "", undefined, valueTokens);
	let output = "";
	for (const emitted of classes) {
		if (emitted.className === "") continue;
		if (output !== "") output += " ";
		output += emitted.className;
	}
	return output;
}
