import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { afterEach, describe, expect, test } from "vitest";
import { examplePreset } from "@yumcss/example-preset";
import { createLibCli, parseLibCommand } from "../src/lib/cli.ts";
import { buildYumCSSLib } from "../src/lib/build.ts";
import { validateYumCSSLibArtifact } from "yumcss/vite/lib-artifact";

const temporaryDirectories: string[] = [];

afterEach(() => {
	for (const directory of temporaryDirectories.splice(0))
		rmSync(directory, { recursive: true, force: true });
});

const makeSourceProject = (): string => {
	const root = mkdtempSync(join(tmpdir(), "yumcss-lib-"));
	temporaryDirectories.push(root);
	mkdirSync(join(root, "src"), { recursive: true });
	writeFileSync(
		join(root, "src", "button.ts"),
		'import { css } from "./design";\n' +
			'export const button = css.class({ $text: { color: "$blue-500" } });\n' +
			'export const panel = css({ display: "flex" });\n',
	);
	return root;
};

describe("yumcss-codemod lib", () => {
	test("parses a deterministic build command", () => {
		const command = parseLibCommand(
			[
				"build",
				"packages/ui",
				"dist/yumcss.lib.json",
				"--include",
				"src/**/*.tsx",
				"--preset-import",
				"./preset.ts",
				"--preset-export",
				"preset",
			],
			"/project",
		);

		expect(command).toMatchObject({
			root: "/project/packages/ui",
			outFile: "/project/packages/ui/dist/yumcss.lib.json",
			sourcePatterns: ["src/**/*.tsx"],
			presetImport: "./preset.ts",
			presetExport: "preset",
		});
	});

	test("parses a named cascade layer for library artifacts", () => {
		const command = parseLibCommand([
			"build",
			".",
			"--cascade",
			"layers",
			"--cascade-layer",
			"app.utilities",
		]);

		expect(command.cascade).toEqual({ mode: "layers", layer: "app.utilities" });
	});

	test("builds a valid artifact from actual css source", () => {
		const root = makeSourceProject();
		const result = buildYumCSSLib({
			root,
			preset: examplePreset,
			sourcePatterns: ["src"],
		});

		expect(result.files).toHaveLength(1);
		expect(result.artifact.rules.atomic).toHaveLength(2);
		expect(result.artifact.rules.atomic.some((rule) => rule.css.includes("color:#3182ce"))).toBe(
			true,
		);
		expect(result.artifact.rules.atomic.some((rule) => rule.css.includes("display:flex"))).toBe(
			true,
		);
		expect(validateYumCSSLibArtifact(result.artifact)).toMatchObject({ valid: true });
	});

	test("runs the CLI with an injected project preset loader", async () => {
		const root = makeSourceProject();
		const cli = createLibCli(
			{
				moduleLoader: {
					importPackage: async <T>() => ({ preset: examplePreset }) as T,
					importFile: async () => undefined,
				},
			},
			root,
		);
		await cli.run([
			"build",
			".",
			"dist/yumcss.lib.json",
			"--preset-import",
			"@acme/preset",
			"--preset-export",
			"preset",
		]);

		const output = join(root, "dist", "yumcss.lib.json");
		expect(validateYumCSSLibArtifact(JSON.parse(readFileSync(output, "utf8")))).toMatchObject({
			valid: true,
		});
	});

	test("refreshes a stale artifact generated by YumCSS", async () => {
		const root = makeSourceProject();
		const output = join(root, "dist", "yumcss.lib.json");
		mkdirSync(join(root, "dist"), { recursive: true });
		writeFileSync(
			output,
			JSON.stringify({
				schema: "yumcss.lib/1",
				generator: "yumcss-codemod lib build",
				hash: "stale",
			}),
		);
		const cli = createLibCli(
			{
				moduleLoader: {
					importPackage: async <T>() => ({ preset: examplePreset }) as T,
					importFile: async () => undefined,
				},
			},
			root,
		);

		await cli.run([
			"build",
			".",
			"dist/yumcss.lib.json",
			"--preset-import",
			"@acme/preset",
			"--preset-export",
			"preset",
		]);

		expect(validateYumCSSLibArtifact(JSON.parse(readFileSync(output, "utf8")))).toMatchObject({
			valid: true,
		});
	});
});
