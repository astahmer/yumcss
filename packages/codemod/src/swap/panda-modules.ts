/** In-place replacement for `const X = panda(tagOrComp, styleOrRecipe)`. */
export function renderFactoryWrapper(options: {
	name: string;
	target: string;
	isRecipe: boolean;
	/** Recipe local/imported binding name (isRecipe only). */
	recipeRef?: string;
	variantKeys?: Array<string>;
	/** Style object text for non-recipe factories (verbatim source slice). */
	styleObjectText?: string;
}): string {
	const tag = /^[A-Z]/.test(options.target) ? options.target : JSON.stringify(options.target);
	const destructured = options.isRecipe
		? ["className", ...(options.variantKeys ?? [])]
		: ["className"];
	const head = `{ ${destructured.join(", ")}, ...rest }`;
	if (options.isRecipe) {
		const recipeArgs = (options.variantKeys ?? []).map((k) => `${k},`).join(" ");
		return [
			`export const ${options.name} = (${head}: Record<string, unknown>) => (`,
			`\t<${tag}`,
			`\t\tclassName={cx(${options.recipeRef}({ ${recipeArgs.replace(/,$/, "")} }), className)}`,
			"\t\t{...rest}",
			"\t/>",
			");",
			"",
		].join("\n");
	}
	return [
		`export const ${options.name} = ({ className, ...rest }: Record<string, unknown>) => (`,
		`\t<${tag} className={cx(css.class(canonicalProps(rest)), className)} />`,
		");",
		"",
	].join("\n");
}

/**
 * `<outDir>/jsx/index.tsx` — layout components wrapping the emitted pattern
 * modules (Stack/HStack/Box/…), plus Box-style direct containers.
 */
export function renderJsxIndex(
	componentNames: ReadonlySet<string>,
	options: ModuleOptions & { aliasSpecifierFor: (subpath: string) => string },
): string {
	const lines: Array<string> = [];
	lines.push("/**");
	lines.push(" * Generated by pandwind-codemod (plan 024): styled-system/jsx layout");
	lines.push(" * components rebuilt over the emitted pattern modules.");
	lines.push(" */");
	lines.push(`import { css, cx } from "${options.cssImport}";`);
	lines.push('import { canonicalProps, splitStyleProps } from "../internal";');

	const PATTERN_OF: Record<string, string> = {
		Stack: "stack",
		HStack: "hstack",
		VStack: "vstack",
		Flex: "flex",
		Grid: "grid",
		Center: "center",
		Circle: "circle",
		Square: "square",
		Wrap: "wrap",
	};
	const usedPatterns = new Set<string>();
	for (const component of componentNames) {
		const pattern = PATTERN_OF[component];
		if (pattern !== undefined && pattern !== "box") usedPatterns.add(pattern);
	}
	for (const pattern of usedPatterns) {
		lines.push(`import { ${pattern} } from "${options.aliasSpecifierFor(`patterns/${pattern}`)}";`);
	}

	lines.push("");
	lines.push("type AnyProps = Record<string, unknown> & { className?: string };");
	lines.push(
		"type PandaRecipe = { base?: Record<string, unknown>; variants?: Record<string, Record<string, Record<string, unknown>>>; defaultVariants?: Record<string, string> } | ((props: any) => string);",
	);
	lines.push('export function panda(tag: import("react").ElementType, recipe: PandaRecipe) {');
	lines.push("\treturn function PandaComponent(props: AnyProps) {");
	lines.push("\t\tconst { className, children, ...rest } = props;");
	lines.push(
		'\t\tif (typeof recipe === "function") { const Tag = tag as import("react").ElementType; return <Tag {...rest} className={cx(recipe(props), className)}>{children}</Tag>; }',
	);
	lines.push("\t\tconst style: Record<string, unknown> = { ...(recipe.base ?? {}) };");
	lines.push(
		"\t\tfor (const [name, values] of Object.entries(recipe.variants ?? {})) { const value = props[name] ?? recipe.defaultVariants?.[name]; if (value !== undefined) Object.assign(style, values[String(value)] ?? {}); }",
	);
	lines.push('\t\tconst Tag = tag as import("react").ElementType;');
	lines.push(
		"\t\treturn <Tag {...splitStyleProps({ ...style, ...rest }).dom} className={cx(css.class(canonicalProps(style)), className)}>{children}</Tag>;",
	);
	lines.push("\t};");
	lines.push("}");
	lines.push("");

	for (const component of componentNames) {
		const pattern = PATTERN_OF[component];
		if (pattern !== undefined) {
			lines.push(`export function ${component}(props: AnyProps) {`);
			lines.push('\tconst { className, as = "div", ...rest } = props;');
			lines.push("\tconst { style, dom } = splitStyleProps(rest);");
			lines.push('\tconst Tag = as as import("react").ElementType;');
			lines.push(`\treturn <Tag {...dom} className={cx(${pattern}(style), className)} />;`);
			lines.push("}");
			lines.push("");
		} else {
			// Box-style container: props ARE declarations.
			lines.push(`export function ${component}(props: AnyProps) {`);
			lines.push('\tconst { className, as = "div", ...rest } = props;');
			lines.push("\tconst { style, dom } = splitStyleProps(rest);");
			lines.push('\tconst Tag = as as import("react").ElementType;');
			lines.push(
				"\treturn <Tag {...dom} className={cx(css.class(canonicalProps(style)), className)} />;",
			);
			lines.push("}");
			lines.push("");
		}
	}
	if (!componentNames.has("Box")) {
		// css still referenced by nothing — keep the import meaningful.
		lines.push("void css;");
	}
	return lines.join("\n") + "\n";
}

