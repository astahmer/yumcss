/** `<outDir>/css.ts` — the single binding every emitted module imports. */
export function renderCssBootstrap(hasPresetFile: boolean): string {
	const presetImport = hasPresetFile
		? 'import { preset } from "./preset";'
		: "// Pass 1 drops the lifted panda preset at ./preset.ts; until then an\n// empty preset keeps the app compiling with raw-CSS passthrough values.";
	return `/**
 * Generated by pandwind-codemod (plan 024): the app's design-css instance.
 * Every migrated/emitted module binds css + cx through this file.
 */
import { createDesignCss } from "pandwind/design";
import { createCx } from "pandwind/cx";
${presetImport}
// Panda projects commonly use custom properties and responsive values that
// are not representable by an empty generated preset. Runtime resolution is
// still provided by createDesignCss; the generated boundary is intentionally
// permissive so migrated source typechecks without hand-written casts.
export const css = createDesignCss(${hasPresetFile ? "preset" : "({} as any)"}) as any;
export const cx = createCx({ css });
`;
}

/** `<outDir>/internal.ts` — runtime shorthand/canonicalization for pattern modules. */
export function renderInternalHelpers(): string {
	const entries = [...PANDA_ALIASES.entries()].map(([k, v]) => `\t${q(k)}: ${q(v)},`).join("\n");
	return `/**
 * Generated by pandwind-codemod (plan 024): runtime key canonicalization
 * shared by emitted pattern modules (panda shorthands -> CSS properties).
 */
const aliases: Record<string, string> = {
${entries}
};

const camel = (prop: string): string =>
	prop.replace(/-(\\w|$)/g, (_m, char: string) => char.toUpperCase());

export function canonicalProps(style: Record<string, unknown>): Record<string, unknown> {
	const out: Record<string, unknown> = {};
	for (const [key, value] of Object.entries(style)) {
		if (value === undefined) continue;
		out[aliases[key] ?? camel(key)] = value;
	}
	return out;
}

const DOM_KEYS = new Set([
	"id", "role", "href", "src", "alt", "title", "target", "rel", "type",
	"name", "value", "disabled", "checked", "tabIndex", "aria-label", "aria-describedby",
]);

/** Split style props from DOM props before a generated wrapper spreads them. */
export function splitStyleProps(props: Record<string, unknown>): {
	style: Record<string, unknown>;
	dom: Record<string, unknown>;
} {
	const style: Record<string, unknown> = {};
	const dom: Record<string, unknown> = {};
	for (const [key, value] of Object.entries(props)) {
		if (/^(data-|aria-|on[A-Z])/.test(key) || DOM_KEYS.has(key)) dom[key] = value;
		else style[key] = value;
	}
	return { style, dom };
}
`;
}

