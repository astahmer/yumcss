function irToCall(ir: SwapIR, meta: PandwindMeta, index = 1): string {
	const result = emitCssClass(ir, meta, { index, tokenRefs: "bare", sort: true });
	if (result.text === "") return "";
	return result.text;
}

function mergeIrs(irs: Array<SwapIR>): SwapIR {
	return {
		entries: irs.flatMap((ir) => ir.entries),
		residuals: irs.flatMap((ir) => ir.residuals),
	};
}

