/** `<outDir>/css.ts` — the single binding every emitted module imports. */
export function renderCssBootstrap(hasPresetFile: boolean): string {
	const presetImport = hasPresetFile
		? 'import { preset } from "./preset";'
		: "// Pass 1 drops the lifted panda preset at ./preset.ts; until then an\n// empty preset keeps the app compiling with raw-CSS passthrough values.";
	return `/**
 * Generated by pandwind-codemod: the app's design-css instance.
 * Every migrated/emitted module binds css + cx through this file.
 */
import { createDesignCss } from "pandwind/design";
import { createCx } from "pandwind/cx";
import { canonicalProps } from "./internal";
${presetImport}
// Panda projects commonly use custom properties and responsive values that
// are not representable by an empty generated preset. Runtime resolution is
// still provided by createDesignCss; the generated boundary is intentionally
// permissive so migrated source typechecks without hand-written casts.
export const css = createDesignCss(${hasPresetFile ? "preset" : "({} as any)"}) as any;
export const cx = createCx({ css });

// Support literal Panda slot recipes whose anatomy list is dynamic
// (for example Ark UI's dialog). The codemod still owns their style objects;
// this small generated resolver only preserves the existing call shape.
const merge = (target: Record<string, unknown>, source: unknown): void => {
	if (typeof source !== "object" || source === null || Array.isArray(source)) return;
	for (const [key, value] of Object.entries(source as Record<string, unknown>)) {
		if (typeof value === "object" && value !== null && !Array.isArray(value)) {
			const branch = typeof target[key] === "object" && target[key] !== null && !Array.isArray(target[key])
				? target[key] as Record<string, unknown>
				: {};
			target[key] = branch;
			merge(branch, value);
		} else target[key] = value;
	}
};

export const sva = (recipe: any) => (props: Record<string, any> = {}) => {
	const slots = Array.isArray(recipe.slots) ? recipe.slots : Object.keys(recipe.base ?? {});
	const output: Record<string, string> = {};
	for (const slot of slots) {
		const style: Record<string, unknown> = {};
		merge(style, recipe.base?.[slot]);
		for (const [name, values] of Object.entries(recipe.variants ?? {})) {
			const value = props[name] ?? recipe.defaultVariants?.[name];
			merge(style, (values as any)?.[String(value)]?.[slot]);
		}
		for (const compound of recipe.compoundVariants ?? []) {
			if (Object.entries(compound).every(([key, value]) => key === "css" || String(props[key] ?? recipe.defaultVariants?.[key]) === String(value))) {
				merge(style, compound.css?.[slot]);
			}
		}
		output[slot] = css.class(canonicalProps(style));
	}
	return output;
};
`;
}

