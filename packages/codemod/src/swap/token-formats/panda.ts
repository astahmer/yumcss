import {
	flattenNestedWithLosses,
	importModule,
	renderTokenTree,
	scalarFormatOutput,
	scalarImportToDocument,
	type ScalarTokenImport,
} from "../token-format-support.ts";
import {
	TokenFormatId,
	type TokenFormatAdapter,
	type TokenFormatLoss,
} from "../token-format-contracts.ts";

const read = async (path: string) => {
	const module = await importModule(path);
	const config = (module.default ?? Object.values(module)[0]) as
		| { theme?: { extend?: { tokens?: unknown }; tokens?: unknown } }
		| undefined;
	const raw = config?.theme?.extend?.tokens ?? config?.theme?.tokens;
	if (typeof raw !== "object" || raw === null)
		throw new Error(`codemod tokens: no panda tokens found in ${path}`);
	const tokens: ScalarTokenImport = {};
	const losses: TokenFormatLoss[] = [];
	for (const [group, value] of Object.entries(raw)) {
		if (typeof value !== "object" || value === null) {
			losses.push({
				path: `/${group}`,
				feature: "token group",
				reason: "Panda token group is not a nested object",
			});
			continue;
		}
		const values: Record<string, string> = {};
		flattenNestedWithLosses(value as Record<string, unknown>, [], values, losses);
		tokens[group] = values;
	}
	return scalarImportToDocument(TokenFormatId.Panda, tokens, path, losses);
};

export const pandaTokenFormat: TokenFormatAdapter = {
	schema: "yumcss.token-format/1",
	id: TokenFormatId.Panda,
	canImport: true,
	canExport: true,
	fidelity: {
		import: "partial",
		export: "partial",
		preserves: ["static scalar token values", "top-level token group"],
		mayLose: [
			"Panda conditions",
			"token aliases",
			"structured values",
			"token metadata",
			"resolver contexts",
		],
	},
	importFile: read,
	export(document) {
		return scalarFormatOutput(
			document,
			(groups) =>
				`// generated by yumcss-codemod tokens\nexport const tokens = {\n${Object.entries(groups)
					.map(([group, values]) => `\t\t${JSON.stringify(group)}: ${renderTokenTree(values)},`)
					.join("\n")}\n};\n`,
		);
	},
};
