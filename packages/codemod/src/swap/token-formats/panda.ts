import type { TokenFormatAdapter, TokenSet } from "../token-format-contracts.ts";
import { createTokenSet, flattenNested, importModule, renderTokenTree } from "../token-format-support.ts";

const read = async (path: string): Promise<TokenSet> => {
	const module = await importModule(path);
	const config = (module.default ?? Object.values(module)[0]) as { theme?: { extend?: { tokens?: unknown }; tokens?: unknown } } | undefined;
	const raw = config?.theme?.extend?.tokens ?? config?.theme?.tokens;
	if (typeof raw !== "object" || raw === null) throw new Error(`codemod tokens: no panda tokens found in ${path}`);
	const out = createTokenSet();
	for (const [group, value] of Object.entries(raw as Record<string, unknown>)) {
		const flat: Record<string, string> = {};
		if (typeof value === "object" && value !== null) flattenNested(value as Record<string, unknown>, [], flat);
		out.groups[group] = flat;
	}
	return out;
};

export const pandaTokenFormat: TokenFormatAdapter = {
	schema: "pandwind.token-format/1",
	id: "panda",
	canImport: true,
	canExport: true,
	importFile: read,
	export: (set) => `// generated by pandwind-codemod tokens\nexport const tokens = {\n${Object.entries(set.groups).map(([group, values]) => `\t\t${JSON.stringify(group)}: ${renderTokenTree(values)},`).join("\n")}\n};\n`,
};
