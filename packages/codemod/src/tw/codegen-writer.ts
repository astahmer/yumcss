import { resolve, relative } from "node:path";
import { readFileSync, writeFileSync } from "node:fs";
import { buildAgentsDocument } from "./agents-json.ts";
import {
	buildGeneratedArtifactManifest,
	GeneratedArtifactOwnershipTag,
	type GeneratedArtifactInput,
} from "./artifact-manifest.ts";
import { extractTwConfigFromSources } from "yumcss/vite/inline";
import { buildYumCSSInteropArtifact } from "./interop-artifact.ts";
import type { TokenDocument } from "../swap/token-document.ts";

export interface GeneratedDesignSystem {
	readonly typesDts: string;
	readonly twTs: string;
	readonly twRuntimeTs: string;
	readonly twConflictsTs: string;
	readonly twBuildTs: string;
	readonly themeBlock: string;
	readonly tokenDocument?: TokenDocument;
	readonly tokenSource?: string;
	readonly utilityCount: number;
	readonly variantCount: number;
}

export interface CodegenWriteOptions {
	readonly outDir: string;
	readonly agents?: boolean;
	readonly projectRoot?: string;
	readonly inputs?: readonly GeneratedArtifactInput[];
}

export class CodegenArtifactWriter {
	write(artifacts: GeneratedDesignSystem, options: CodegenWriteOptions): void {
		writeFileSync(resolve(options.outDir, "types.d.ts"), artifacts.typesDts);
		writeFileSync(resolve(options.outDir, "tw.ts"), artifacts.twTs);
		writeFileSync(resolve(options.outDir, "tw.runtime.ts"), artifacts.twRuntimeTs);
		writeFileSync(resolve(options.outDir, "tw.conflicts.ts"), artifacts.twConflictsTs);
		writeFileSync(resolve(options.outDir, "tw.build.ts"), artifacts.twBuildTs);
		writeFileSync(
			resolve(options.outDir, "yumcss.interop.json"),
			`${JSON.stringify(
				buildYumCSSInteropArtifact({
					typesDts: artifacts.typesDts,
					twTs: artifacts.twTs,
					twRuntimeTs: artifacts.twRuntimeTs,
					twConflictsTs: artifacts.twConflictsTs,
					twBuildTs: artifacts.twBuildTs,
					themeBlock: artifacts.themeBlock,
					tokenDocument: artifacts.tokenDocument,
					tokenSource: artifacts.tokenSource,
				}),
				null,
				"\t",
			)}\n`,
		);
		if (options.agents === true) {
			const config = extractTwConfigFromSources([
				artifacts.twTs,
				artifacts.twRuntimeTs,
				artifacts.twBuildTs,
			]);
			if (config === undefined)
				throw new Error("yumcss-codemod tw generate: could not extract config for agents.json");
			const doc = buildAgentsDocument({
				typesDts: artifacts.typesDts,
				config,
				themeBlock: artifacts.themeBlock,
			});
			writeFileSync(
				resolve(options.outDir, "yumcss.agents.json"),
				`${JSON.stringify(doc, null, "\t")}\n`,
			);
		}
		if (artifacts.themeBlock !== "")
			writeFileSync(
				resolve(options.outDir, "yumcss-theme.css"),
				`/* Generated by yumcss — runtime stylesheet. Regenerate with yumcss-codemod tw generate. */\n${artifacts.themeBlock}\n`,
			);
		this.writeManifest(options);
	}

	writeManifest(options: CodegenWriteOptions): void {
		const projectRoot = options.projectRoot ?? options.outDir;
		const files = [
			["types.d.ts", GeneratedArtifactOwnershipTag.Editor],
			["tw.ts", GeneratedArtifactOwnershipTag.Runtime],
			["tw.runtime.ts", GeneratedArtifactOwnershipTag.Optional],
			["tw.conflicts.ts", GeneratedArtifactOwnershipTag.Optional],
			["tw.build.ts", GeneratedArtifactOwnershipTag.BuildOnly],
			["yumcss.interop.json", GeneratedArtifactOwnershipTag.BuildOnly],
			["yumcss-theme.css", GeneratedArtifactOwnershipTag.Runtime],
			["yumcss.agents.json", GeneratedArtifactOwnershipTag.Editor],
			["bridge.ts", GeneratedArtifactOwnershipTag.Optional],
		] as const;
		const artifacts = files.flatMap(([name, ownership]) => {
			const path = resolve(options.outDir, name);
			try {
				return [
					{
						path: relative(projectRoot, path).replaceAll("\\", "/"),
						ownership,
						content: readFileSync(path, "utf8"),
					},
				];
			} catch {
				return [];
			}
		});
		const manifest = buildGeneratedArtifactManifest({
			inputs: (options.inputs ?? []).map((input) => ({
				...input,
				path: relative(projectRoot, input.path).replaceAll("\\", "/"),
			})),
			artifacts,
		});
		writeFileSync(
			resolve(options.outDir, "yumcss.generated.json"),
			`${JSON.stringify(manifest, null, "\t")}\n`,
		);
	}
}
