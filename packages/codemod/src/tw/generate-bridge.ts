/**
 * Tailwind bridge generation — generates the optional `bridge.ts` artifact for
 * the YumCSS css() adapter.
 *
 * The bridge is the inverted Tailwind design system scoped to what the
 * app's preset can produce: `(property, resolved value) -> utility`. It is
 * generated from the app's real `tailwind.css` (so `@theme` mirrors become
 * short utilities) and only keeps theme-derived values the preset tokens
 * can emit — literal values (flex, relative, ...) always stay.
 *
 * YumCSS never imports this module automatically. The generated module
 * exports `bridge`, the `variants` metadata and a ready `twAdapter`
 * (`createTwAdapter` bound to the preset). It becomes a runtime dependency
 * only when an application explicitly selects Tailwind class output as its
 * ClassNameStrategy; ordinary YumCSS css()/tw() runtime code does not need
 * it. When it is selected, app code and the Vite plugin can share one instance:
 *
 *   import { twAdapter } from "./bridge";
 *   export const dss = createDesignCss(examplePreset, { className: twAdapter });
 *   // vite.config.ts
 *   plugins: [yumcssExtractVite(examplePreset, { className: twAdapter }), ...]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { BRIDGE_PROPS, generateUtilityBridge } from "./bridge.ts";
import { extractTwConfigFromSources } from "yumcss/vite/inline";
import {
	buildYumCSSInteropArtifact,
	parseYumCSSInteropArtifact,
	YUMCSS_INTEROP_SCHEMA,
	type YumCSSInteropTokenSnapshot,
} from "./interop-artifact.ts";
import { loadTokenDocument } from "./codegen-theme-input.ts";

export interface GenerateTwBridgeOptions {
	readonly cssEntry: string;
	readonly twFile: string;
	readonly twRuntimeFile?: string;
	readonly twConflictsFile?: string;
	readonly twBuildFile?: string;
	readonly outFile: string;
	readonly presetImport: string;
	readonly presetExport: string;
}

export interface GeneratedTwBridge {
	readonly outFile: string;
	readonly interopFile?: string;
	readonly propertyCount: number;
}

export interface TwBridgeGenerator {
	generate(options: GenerateTwBridgeOptions): Promise<GeneratedTwBridge>;
}

type PresetModule = {
	readonly tokens?: Record<string, Record<string, unknown>>;
};

class DefaultTwBridgeGenerator implements TwBridgeGenerator {
	async generate(options: GenerateTwBridgeOptions): Promise<GeneratedTwBridge> {
		const css = readFileSync(options.cssEntry, "utf8");
		const preset = (await import(options.presetImport))[options.presetExport] as PresetModule;

		// Only values proven by the target preset can be shortened to a token
		// utility. Literal CSS values remain available through the bridge's
		// property-preserving fallback.
		const values = new Set<string>();
		for (const group of Object.values(preset.tokens ?? {})) {
			for (const value of Object.values(group)) {
				if (typeof value === "string") values.add(value);
			}
		}

		const bridge = await generateUtilityBridge(css, resolve(options.cssEntry, ".."), {
			props: BRIDGE_PROPS,
			values,
		});

		const runtimeFile = options.twRuntimeFile ?? resolve(dirname(options.twFile), "tw.runtime.ts");
		const conflictsFile =
			options.twConflictsFile ?? resolve(dirname(options.twFile), "tw.conflicts.ts");
		const buildFile = options.twBuildFile ?? resolve(dirname(options.twFile), "tw.build.ts");
		const twSource = readFileSync(options.twFile, "utf8");
		const twRuntimeSource = existsSync(runtimeFile) ? readFileSync(runtimeFile, "utf8") : undefined;
		const twConflictsSource = existsSync(conflictsFile)
			? readFileSync(conflictsFile, "utf8")
			: undefined;
		const twBuildSource = existsSync(buildFile) ? readFileSync(buildFile, "utf8") : undefined;
		const twSources = [
			twSource,
			...(twRuntimeSource === undefined ? [] : [twRuntimeSource]),
			...(twConflictsSource === undefined ? [] : [twConflictsSource]),
			...(twBuildSource === undefined ? [] : [twBuildSource]),
		];
		const config = extractTwConfigFromSources(twSources);
		if (config === undefined) {
			throw new Error(`yumcss: could not read the tw() config from ${options.twFile}`);
		}

		const out = `// Generated by yumcss — do not edit. Run \`yumcss-codemod tw generate --bridge\` to regenerate.
// This optional bridge is not imported by YumCSS automatically.
// Import it only when the app explicitly selects twAdapter for Tailwind class output.
// The bridge and its metadata are otherwise build-time/tooling artifacts.
import { createTwAdapter } from "yumcss/tw";
import { ${options.presetExport} } from "${options.presetImport}";

/** (property, resolved value) -> Tailwind utility, scoped to the preset. */
export const bridge = ${JSON.stringify(bridge)} as const;

/** Variant metadata mirrored from the generated tw runtime artifacts. */
export const variants = ${JSON.stringify(config.variants)} as const;

/** css() class strategy: emit the same utilities tw() emits. */
export const twAdapter = createTwAdapter({
	preset: ${options.presetExport},
	variants,
	bridge,
});
`;

		const interopPath = resolve(dirname(options.outFile), "yumcss.interop.json");
		const typesPath = resolve(dirname(options.twFile), "types.d.ts");
		if (existsSync(typesPath)) {
			const themePath = resolve(dirname(options.outFile), "yumcss-theme.css");
			const existingInterop = existsSync(interopPath)
				? (JSON.parse(readFileSync(interopPath, "utf8")) as Record<string, unknown>)
				: undefined;
			let tokenSnapshot: YumCSSInteropTokenSnapshot | undefined;
			let tokenDocument = undefined;
			if (existingInterop?.schema === YUMCSS_INTEROP_SCHEMA) {
				tokenSnapshot = parseYumCSSInteropArtifact(existingInterop).tokens;
			} else {
				if (existingInterop !== undefined)
					throw new Error(
						`yumcss-codemod tw bridge: unsupported existing interop schema '${String(existingInterop.schema)}'`,
					);
				tokenDocument = await loadTokenDocument(options.presetImport, dirname(options.twFile));
			}
			const artifact = buildYumCSSInteropArtifact({
				typesDts: readFileSync(typesPath, "utf8"),
				twTs: twSource,
				twRuntimeTs: twRuntimeSource,
				twConflictsTs: twConflictsSource,
				twBuildTs: twBuildSource,
				bridge,
				themeBlock: existsSync(themePath) ? readFileSync(themePath, "utf8") : "",
				...(tokenSnapshot === undefined
					? { tokenDocument, tokenSource: options.presetImport }
					: { tokenSnapshot }),
			});
			writeFileSync(options.outFile, out);
			writeFileSync(interopPath, `${JSON.stringify(artifact, null, "\t")}\n`);
			return {
				outFile: options.outFile,
				interopFile: interopPath,
				propertyCount: Object.keys(bridge).length,
			};
		}

		writeFileSync(options.outFile, out);
		return { outFile: options.outFile, propertyCount: Object.keys(bridge).length };
	}
}

const createTwBridgeGenerator = (): TwBridgeGenerator => new DefaultTwBridgeGenerator();

export const generateTwBridge = async (
	options: GenerateTwBridgeOptions,
): Promise<GeneratedTwBridge> => createTwBridgeGenerator().generate(options);
